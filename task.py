llm = ChatGoogleGenerativeAI(
    model="gemini-3.5-flash-lite",
    temperature=0.2
)

"""Task-1 : KLG Ancient World"""

from langchain_core.prompts import ChatPromptTemplate, MessagesPlaceholder
from langchain_core.output_parsers import StrOutputParser

BUSINESS_NAME = "KLG Ancient World"

SYSTEM_V1 = """ROLE:   You are the friendly assistant for KLG Ancient World (klgancientworld.com).
FACTS:  We leverage AI in cultural heritage to extract and preserve lost ancient knowledge.
        Ancient scripts studied: Brahmi, Grantha, Latin, and Sanskrit.
        Narratives covered: Puranic narratives and Sthala Puranas.
        Sacred Landscape Routes: Alqueva and St. Peter of the Orchards.
        App: MythiLens is our heritage exploration app with quest, learning, and offline capabilities.
RULES:  Never promise unstated tour dates, ticket prices, or unverified archaeological claims.
        If the answer isn't in FACTS, say "I'll check with the KLG team."
FORMAT: Under 50 words, friendly, English or Telugu matching the user."""

prompt = ChatPromptTemplate.from_messages([
    ("system", SYSTEM_V1),
    MessagesPlaceholder("history"),
    ("human", "{question}"),
])

chain = prompt | llm | StrOutputParser()

history = []
def ask(question: str) -> str:
    answer = chain.invoke({
        "business": BUSINESS_NAME,
        "history": history,
        "question": question,
    })
    history.extend([("human", question), ("ai", answer)])
    return answer

print(ask("Hi, I'm Karthikeya. Which ancient scripts do you study?"))
print(ask("What's my name?"))

"""Task-2 : Tests"""

import csv
def run_tests(active_chain, path: str = "/content/test.csv") -> float:
    rows = list(csv.DictReader(open(path, newline="", encoding="utf-8")))
    passed = 0
    for row in rows:
        answer = active_chain.invoke({
            "business": BUSINESS_NAME,
            "history": [],
            "question": row["question"],
        })
        ok = row["must_include"].lower() in answer.lower()
        passed += ok
        print("PASS" if ok else "FAIL", "|", row["question"], "→", answer[:70])
    rate = passed / len(rows)
    print(f"\n{passed}/{len(rows)} passed ({rate:.0%})")
    return rate

rate_v1 = run_tests(chain)

"""Task-3 : Improve"""

# 1. Baseline pass rate (using SYSTEM_V1 and chain from Task 1 & Task 2)
